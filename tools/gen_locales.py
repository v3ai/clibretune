#!/usr/bin/env python3
"""gen_locales.py - emit src/app/i18n_data.c from the stock LibreTune locale files
(ref/LibreTune/crates/libretune-app/src/i18n/locales/<lang>/*.json) plus the extra
strings of this port in tools/locales_extra.tsv (English <TAB> pt-BR <TAB> hu-HU).

Usage: tools/gen_locales.py [locales_dir] > src/app/i18n_data.c
The key of a string is its English text with "..." for the ellipsis and without
the "\\t<shortcut>" suffix; `{{x}}` placeholders are left alone.  Output tables are
sorted by byte value so lt_tr can binary-search them with strcmp.
"""
import json
import os
import re
import sys

LANGS = [("en", "English"), ("pt-BR", "Português (Brasil)"), ("hu-HU", "Magyar")]
FILES = ["common", "dialog", "errors", "menu"]


def norm(s):
    s = s.split("\t")[0]
    return s.replace("…", "...")


def flat(d, p=""):
    for k, v in d.items():
        if isinstance(v, dict):
            yield from flat(v, p + k + ".")
        else:
            yield p + k, v


def cesc(s):
    out = []
    for b in s.encode("utf-8"):
        c = chr(b)
        if c == '"' or c == "\\":
            out.append("\\" + c)
        elif 32 <= b < 127:
            out.append(c)
        else:
            out.append("\\%03o" % b)
    return "".join(out)


# This program is clibretune; the stock text calls it LibreTune.  Links to the original project
# and the original's own source paths keep that name.
_BRAND_KEEP = re.compile(r"RallyPat/LibreTune|libretune_core|libretune-app|crates/libretune[-\w]*")


def brand(text):
    keep = []

    def hold(m):
        keep.append(m.group(0))
        return "\x00%d\x00" % (len(keep) - 1)
    text = _BRAND_KEEP.sub(hold, text)
    text = re.sub(r"(?<![A-Za-z_])(?:LibreTune|libretune)", "clibretune", text)
    return re.sub("\x00(\\d+)\x00", lambda m: keep[int(m.group(1))], text)


def main():
    base = sys.argv[1] if len(sys.argv) > 1 else \
        "ref/LibreTune/crates/libretune-app/src/i18n/locales"
    tabs = {c: {} for c, _ in LANGS[1:]}
    en_flat = {}
    for f in FILES:
        en_flat.update({f + "." + k: v for k, v in flat(json.load(open("%s/en/%s.json" % (base, f))))})
    for code in tabs:
        tr = {}
        for f in FILES:
            tr.update({f + "." + k: v for k, v in flat(json.load(open("%s/%s/%s.json" % (base, code, f))))})
        for k, en in en_flat.items():
            if k in tr and norm(tr[k]) != norm(en):
                tabs[code][brand(norm(en))] = brand(norm(tr[k]))
    here = os.path.dirname(os.path.abspath(__file__))
    for line in open(os.path.join(here, "locales_extra.tsv"), encoding="utf-8"):
        line = line.rstrip("\n")
        if not line or line.startswith("#"):
            continue
        cols = line.split("\t")
        if len(cols) != 3:
            sys.exit("bad extras line: %r" % line)
        for code, v in zip(("pt-BR", "hu-HU"), cols[1:]):
            if v:
                tabs[code].setdefault(cols[0], v)
    w = sys.stdout.write
    w("/* i18n_data.c - embedded language tables.  GENERATED by tools/gen_locales.py from the\n")
    w(" * stock LibreTune locales (en, pt-BR, hu-HU) and tools/locales_extra.tsv, DO NOT EDIT.\n")
    w(" * SPDX-License-Identifier: GPL-2.0-or-later\n */\n")
    w('#include "i18n.h"\n\n')
    for code, _ in LANGS[1:]:
        ident = code.replace("-", "_")
        items = sorted(tabs[code].items(), key=lambda kv: kv[0].encode("utf-8"))
        w("static const lt_i18n_pair tab_%s[] = {\n" % ident)
        for en, tr in items:
            if len(en.encode()) > 400 or len(tr.encode()) > 400:
                sys.exit("string too long: " + en)
            w('    { "%s",\n      "%s" },\n' % (cesc(en), cesc(tr)))
        w("};\n\n")
    w("const lt_i18n_lang lt_i18n_langs[LT_I18N_NLANG] = {\n")
    w('    { "en", "English", NULL, 0 },\n')
    for code, name in LANGS[1:]:
        ident = code.replace("-", "_")
        w('    { "%s", "%s", tab_%s, (int)(sizeof(tab_%s) / sizeof(tab_%s[0])) },\n'
          % (code, cesc(name), ident, ident, ident))
    w("};\n")


if __name__ == "__main__":
    main()
