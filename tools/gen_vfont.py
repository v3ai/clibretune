#!/usr/bin/env python3
"""Generate src/gui/font_vec.c from Hershey 'rowmans.jhf' (Roman Simplex).
Usage: gen_vfont.py ref/fonts/rowmans.jhf src/gui/font_vec.c
Glyph 1..95 = ASCII 32..126, glyph 96 = degree sign (U+00B0).
"""
import sys

def parse(path):
    glyphs = []
    for line in open(path):
        line = line.rstrip("\n")
        if len(line) < 10:
            continue
        n = int(line[5:8])
        body = line[8:]
        left = ord(body[0]) - ord('R')
        right = ord(body[1]) - ord('R')
        pts = []
        pairs = body[2:2 + 2 * (n - 1)]
        for i in range(0, len(pairs), 2):
            a, b = pairs[i], pairs[i + 1]
            if a == ' ' and b == 'R':
                pts.append(None)
            else:
                pts.append((ord(a) - ord('R') - left, ord(b) - ord('R')))
        glyphs.append((right - left, pts))
    return glyphs

def main():
    g = parse(sys.argv[1])
    assert len(g) == 96, len(g)
    data, offs, adv = [], [], []
    for w, pts in g:
        offs.append(len(data) // 2)
        adv.append(w)
        for p in pts:
            if p is None:
                data += [-128, 0]
            else:
                data += [p[0], p[1]]
    offs.append(len(data) // 2)
    o = []
    o.append("/* font_vec.c - vector stroke font (generated by tools/gen_vfont.py).\n"
             " *\n"
             " * Glyph data: Hershey Roman Simplex (rowmans.jhf), Copyright 1967\n"
             " * Dr. A. V. Hershey and James Hurt (NBS); distribution by Kamal Mostafa.\n"
             " * The Hershey Fonts may be used by anyone for any purpose, provided this\n"
             " * attribution is retained.\n"
             " * Each glyph: (x,y) pairs, x relative to left bearing, y down, baseline y=9,\n"
             " * cap top y=-12; pair (-128,0) = pen up.\n"
             " * DO NOT EDIT BY HAND.\n"
             " * SPDX-License-Identifier: GPL-2.0-or-later\n"
             " */\n")
    o.append('#include "gui.h"\n')
    o.append("/* index 0..94 = ASCII 32..126, 95 = degree sign */")
    o.append("const lt_u8 lt_vfont_adv[96] = {")
    o.append("    " + ", ".join(str(a) for a in adv))
    o.append("};\n")
    o.append("const lt_u16 lt_vfont_off[97] = {")
    for i in range(0, 97, 12):
        o.append("    " + ", ".join(str(x) for x in offs[i:i+12]) + ("," if i + 12 < 97 else ""))
    o.append("};\n")
    o.append("const lt_s8 lt_vfont_data[%d] = {" % len(data))
    for i in range(0, len(data), 24):
        o.append("    " + ", ".join(str(x) for x in data[i:i+24]) + ("," if i + 24 < len(data) else ""))
    o.append("};\n")
    open(sys.argv[2], "w").write("\n".join(o))
    print("wrote", sys.argv[2], len(data) // 2, "points")

main()
