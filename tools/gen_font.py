#!/usr/bin/env python3
"""Generate src/gui/font8x16.c from GNU Unifont .hex (narrow 8x16 glyphs only).
Usage: gen_font.py ref/fonts/unifont-X.hex src/gui/font8x16.c
"""
import sys

RANGES = [(0x20, 0x7E), (0xA0, 0xFF), (0x2190, 0x2193), (0x2026, 0x2026),
          (0x2500, 0x257F), (0x2580, 0x259F), (0xFFFD, 0xFFFD)]

def wanted(cp):
    for a, b in RANGES:
        if a <= cp <= b:
            return True
    return False

def main():
    src, dst = sys.argv[1], sys.argv[2]
    glyphs = {}
    ver = src.split("unifont-")[-1].replace(".hex", "")
    with open(src) as f:
        for line in f:
            line = line.strip()
            if not line or ":" not in line:
                continue
            cp_s, data = line.split(":", 1)
            cp = int(cp_s, 16)
            if len(data) != 32 or not wanted(cp):
                continue
            glyphs[cp] = bytes.fromhex(data)
    cps = sorted(glyphs)
    o = []
    o.append("/* font8x16.c - built-in 8x16 bitmap font (generated by tools/gen_font.py).\n"
             " *\n"
             " * Glyph data derived from GNU Unifont %s (https://unifoundry.com/unifont/),\n"
             " * Copyright (C) Roman Czyborra, Paul Hardy, et al.\n"
             " * Licensed GPL-2.0-or-later WITH the GNU Unifont font embedding exception:\n"
             " * a document or program that merely embeds the font does not become covered\n"
             " * by the GPL on account of that.  Only narrow (8x16) glyphs are included.\n"
             " * DO NOT EDIT BY HAND; regenerate with tools/gen_font.py.\n"
             " * SPDX-License-Identifier: GPL-2.0-or-later\n"
             " */\n" % ver)
    o.append('#include "gui.h"\n')
    o.append("#define LT_FONT_COUNT %d\n" % len(cps))
    o.append("static const lt_u16 font_cp[LT_FONT_COUNT] = {")
    for i in range(0, len(cps), 10):
        o.append("    " + ", ".join("0x%04X" % c for c in cps[i:i+10]) +
                 ("," if i + 10 < len(cps) else ""))
    o.append("};\n")
    o.append("static const lt_u8 font_bits[LT_FONT_COUNT][16] = {")
    for n, c in enumerate(cps):
        row = ", ".join("0x%02X" % b for b in glyphs[c])
        o.append("    {%s}%s /* U+%04X */" % (row, "," if n + 1 < len(cps) else "", c))
    o.append("};\n")
    o.append("""static int font_find(lt_u32 cp)
{
    int lo = 0, hi = LT_FONT_COUNT - 1, mid;
    while (lo <= hi) {
        mid = (lo + hi) / 2;
        if (font_cp[mid] == cp) {
            return mid;
        }
        if (font_cp[mid] < cp) {
            lo = mid + 1;
        } else {
            hi = mid - 1;
        }
    }
    return -1;
}

const lt_u8 *lt_font_glyph(lt_u32 cp)
{
    int i;
    if (cp < 0x7F && cp >= 0x20) {
        /* ASCII is dense and starts at index 0 */
        return font_bits[cp - 0x20];
    }
    i = font_find(cp);
    if (i < 0) {
        i = font_find((lt_u32)'?');
    }
    return font_bits[i];
}

lt_u32 lt_utf8_next(const char **s)
{
    const unsigned char *p = (const unsigned char *)*s;
    lt_u32 c = *p, cp;
    int n, i;
    if (c == 0) {
        return 0;
    }
    if (c < 0x80) {
        *s += 1;
        return c;
    }
    if (c >= 0xC2 && c <= 0xDF) {
        n = 1; cp = c & 0x1F;
    } else if (c >= 0xE0 && c <= 0xEF) {
        n = 2; cp = c & 0x0F;
    } else if (c >= 0xF0 && c <= 0xF4) {
        n = 3; cp = c & 0x07;
    } else {
        *s += 1;
        return 0xFFFD;
    }
    for (i = 1; i <= n; i++) {
        if ((p[i] & 0xC0) != 0x80) {
            *s += i;
            return 0xFFFD;
        }
        cp = (cp << 6) | (lt_u32)(p[i] & 0x3F);
    }
    *s += n + 1;
    if ((n == 2 && cp < 0x800) || (n == 3 && cp < 0x10000) ||
        cp > 0x10FFFF || (cp >= 0xD800 && cp <= 0xDFFF)) {
        return 0xFFFD;
    }
    return cp;
}
""")
    with open(dst, "w") as f:
        f.write("\n".join(o))
    print("wrote %s: %d glyphs" % (dst, len(cps)))

main()
