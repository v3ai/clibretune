#!/usr/bin/env python3
"""fetch_definitions.py - download the ECU definitions (INI files) that clibretune bundles.

    python3 tools/fetch_definitions.py              fetch what assets/definitions/*/sources.json
                                                    lists into build/definitions/ (sha256 checked)
    python3 tools/fetch_definitions.py --discover   ask GitHub what the pinned releases/tags hold
                                                    and rewrite the sources.json manifests
    python3 tools/fetch_definitions.py --family F   only family F (speeduino, rusefi, fome, miata-ecus)

The files are NOT kept in git (they are tens of megabytes); the manifests are. Each manifest
entry records where a file comes from (URL, member inside a release zip, tag and commit), its
size, sha256, signature and licence, so the bundle can be rebuilt byte for byte. When an upstream
copy has gone (GitHub Actions artifacts expire), `python3 tools/gen_definitions.py --extract`
unpacks the files from the committed src/project/inidb_data.c instead.

Release zips are not downloaded whole: the INI member is read with HTTP range requests (the zip
central directory and the one member), so a 66 MB rusEFI bundle costs about 0.5 MB.
Network: GitHub API (set GITHUB_TOKEN, or have `gh` logged in, for higher limits; Actions
artifacts always need a token), github.com release downloads, raw.githubusercontent.com.
"""
import hashlib
import io
import json
import os
import re
import subprocess
import sys
import urllib.error
import urllib.request
import zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ASSETS = os.path.join(ROOT, "assets", "definitions")
CACHE = os.path.join(ROOT, "build", "definitions")
API = "https://api.github.com"
UA = "clibretune-fetch-definitions"

# ---- what is bundled (pinned) ------------------------------------------------------------
SPEEDUINO = {
    "repo": "speeduino/speeduino",
    "path": "reference/speeduino.ini",
    "licence": "GPL-2.0",
    # every release tag since 201712; "20208" is a mistyped duplicate of 202008 and is skipped
    "first": "201712",
    "skip": ["20208"],
}
RUSEFI = {
    "repo": "rusefi/rusefi",
    "licence": "GPL-3.0 (with the rusEFI additional terms, see license.txt)",
    # latest stable release (all boards) plus the two before it: exact matches for anyone on a
    # release, and a close same-board neighbour for everyone else
    "releases": ["release_20260812", "release_20260220_2", "release_20251018"],
    "asset": r"^rusefi_bundle_(.+)\.zip$",
    "skip_asset": r"_autoupdate\.zip$|_debug\.zip$|_obfuscated",
    "member": r"(^|/)rusefi_[^/]*\.ini$",
}
FOME = {
    "repo": "FOME-Tech/fome-fw",
    "licence": "GPL-3.0 (with the rusEFI additional terms, see LICENSE)",
    "releases": ["release_260501_02"],
    "asset": r"^fome_bundle_(.+)\.zip$",
    "skip_asset": r"_autoupdate\.zip$|_debug\.zip$",
    "member": r"(^|/)fome_[^/]*\.ini$",
}
MIATA = {
    "repo": "v3ai/miata-ecus",
    "licence": "GPL-3.0 (generated by rusEFI from the MIT-licensed board files)",
    "run": 44696916909,
    "artifact": "rusefi_miata-ecu.ini",
}


def token():
    t = os.environ.get("GITHUB_TOKEN", "")
    if t:
        return t
    try:
        return subprocess.run(["gh", "auth", "token"], capture_output=True, text=True,
                              check=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return ""


def http(url, headers=None, method="GET", auth=False):
    h = {"User-Agent": UA}
    if auth:
        t = token()
        if t:
            h["Authorization"] = "Bearer " + t
    h.update(headers or {})
    return urllib.request.urlopen(urllib.request.Request(url, headers=h, method=method))


def api(path):
    out = []
    url = API + "/" + path
    while url:
        with http(url, {"Accept": "application/vnd.github+json"}, auth=True) as r:
            data = json.load(r)
            link = r.headers.get("Link", "") or ""
        if isinstance(data, list):
            out.extend(data)
        else:
            return data
        m = re.search(r'<([^>]+)>; rel="next"', link)
        url = m.group(1) if m else None
    return out


class HttpFile(io.RawIOBase):
    """read-only seekable file over HTTP range requests"""

    def __init__(self, url):
        super().__init__()
        with http(url, method="HEAD") as r:
            self.final = r.geturl()
            self.size = int(r.headers["Content-Length"])
        self.pos = 0

    def seekable(self):
        return True

    def readable(self):
        return True

    def tell(self):
        return self.pos

    def seek(self, off, whence=0):
        self.pos = off if whence == 0 else (self.pos + off if whence == 1 else self.size + off)
        return self.pos

    def readinto(self, b):
        n = min(len(b), self.size - self.pos)
        if n <= 0:
            return 0
        with http(self.final, {"Range": "bytes=%d-%d" % (self.pos, self.pos + n - 1)}) as r:
            d = r.read()
        b[:len(d)] = d
        self.pos += len(d)
        return len(d)


def zip_member(url, pattern):
    """(member name, bytes) of the one member matching pattern"""
    z = zipfile.ZipFile(io.BufferedReader(HttpFile(url), buffer_size=1 << 16))
    names = [i.filename for i in z.infolist() if re.search(pattern, i.filename)]
    if len(names) != 1:
        raise SystemExit("%s: %d members match %s" % (url, len(names), pattern))
    return names[0], z.read(names[0])


def ini_signature(data):
    m = re.search(rb'^\s*signature\s*=\s*"([^"]*)"', data, re.M)
    if m is None:
        m = re.search(rb'^\s*signature\s*=\s*([^;\r\n]*)', data, re.M)
    return m.group(1).decode("latin-1").strip() if m else ""


def sha256(data):
    return hashlib.sha256(data).hexdigest()


def manifest_path(fam):
    return os.path.join(ASSETS, fam, "sources.json")


def save(fam, entries):
    os.makedirs(os.path.join(ASSETS, fam), exist_ok=True)
    with open(manifest_path(fam), "w", encoding="utf-8", newline="\n") as f:
        json.dump(entries, f, indent=1, ensure_ascii=True)
        f.write("\n")
    print("%s: %d files" % (manifest_path(fam), len(entries)))


def store(rel, data):
    p = os.path.join(CACHE, rel)
    os.makedirs(os.path.dirname(p), exist_ok=True)
    with open(p, "wb") as f:
        f.write(data)


def tag_key(t):
    m = re.match(r"^(\d{6})(?:[.-]?([0-9a-z]+))?$", t)
    if not m:
        return (0, "")
    return (int(m.group(1)), m.group(2) or "")


def discover_speeduino():
    cfg = SPEEDUINO
    tags = api("repos/%s/tags?per_page=100" % cfg["repo"])
    out, seen = [], {}
    for t in sorted(tags, key=lambda t: tag_key(t["name"])):
        name = t["name"]
        if name in cfg["skip"] or tag_key(name) < tag_key(cfg["first"]):
            continue
        sha = t["commit"]["sha"]
        url = "https://raw.githubusercontent.com/%s/%s/%s" % (cfg["repo"], sha, cfg["path"])
        with http(url) as r:
            data = r.read()
        h = sha256(data)
        if h in seen:               # point release with an unchanged INI: one file, both tags
            seen[h]["tags"].append(name)
            continue
        e = {"file": "speeduino/speeduino_%s.ini" % name, "family": "speeduino",
             "board": "", "version": name, "tags": [name], "commit": sha,
             "url": url, "member": "", "signature": ini_signature(data),
             "size": len(data), "sha256": h, "licence": cfg["licence"],
             "source": "https://github.com/%s/blob/%s/%s" % (cfg["repo"], name, cfg["path"])}
        seen[h] = e
        out.append(e)
        store(e["file"], data)
        print("  %-32s %8d %s" % (e["file"], len(data), e["signature"]))
    save("speeduino", out)


def cached(prev, url):
    """(member, bytes) from an earlier discovery of the same URL whose cached copy is intact"""
    e = prev.get(url)
    if e is None:
        return None
    p = os.path.join(CACHE, e["file"])
    if not os.path.exists(p):
        return None
    with open(p, "rb") as f:
        data = f.read()
    return (e["member"], data) if sha256(data) == e["sha256"] else None


def discover_bundles(fam, cfg):
    out = []
    prev = {}
    if os.path.exists(manifest_path(fam)):
        with open(manifest_path(fam), encoding="utf-8") as f:
            for e in json.load(f):
                prev[e["url"]] = e
                for u in e.get("same_as", []):
                    prev[u["url"]] = dict(e, member=u["member"])
    for rel in cfg["releases"]:
        r = api("repos/%s/releases/tags/%s" % (cfg["repo"], rel))
        commit = ""
        try:
            ref = api("repos/%s/commits/%s" % (cfg["repo"], rel))
            commit = ref.get("sha", "")
        except Exception:      # noqa: BLE001 - commit lookup is informative only
            commit = ""
        seen = {}
        for a in sorted(r["assets"], key=lambda a: a["name"]):
            m = re.match(cfg["asset"], a["name"])
            if m is None or re.search(cfg["skip_asset"], a["name"]):
                continue
            board = m.group(1)
            url = a["browser_download_url"]
            got = cached(prev, url)
            if got is None:
                try:
                    got = zip_member(url, cfg["member"])
                except SystemExit as ex:      # a bundle without an INI (console-only bundles)
                    print("  skipped %s: %s" % (a["name"], ex))
                    continue
            member, data = got
            h = sha256(data)
            if h in seen:           # the same INI in two bundles (e.g. with/without bootloader)
                seen[h]["same_as"].append({"board": board, "url": url, "member": member})
                print("  %-48s same as %s" % (a["name"], seen[h]["file"]))
                continue
            e = {"file": "%s/%s/%s/%s" % (fam, rel, board, os.path.basename(member)),
                 "family": fam, "board": board, "version": rel, "tags": [rel],
                 "commit": commit, "url": url, "member": member,
                 "signature": ini_signature(data), "size": len(data), "sha256": h,
                 "licence": cfg["licence"], "source": r["html_url"], "same_as": []}
            seen[h] = e
            out.append(e)
            store(e["file"], data)
            print("  %-56s %8d %s" % (e["file"], len(data), e["signature"]))
    save(fam, out)


class _NoRedirect(urllib.request.HTTPRedirectHandler):
    def redirect_request(self, req, fp, code, msg, headers, newurl):
        return None


def signed_url(url):
    """the storage URL an authenticated API download redirects to (fetched without the token)"""
    opener = urllib.request.build_opener(_NoRedirect)
    req = urllib.request.Request(url, headers={"User-Agent": UA,
                                               "Authorization": "Bearer " + token()})
    try:
        opener.open(req)
    except urllib.error.HTTPError as e:
        if e.code in (301, 302, 303, 307, 308):
            return e.headers["Location"]
        raise
    raise SystemExit("%s: expected a redirect" % url)


def artifact_bytes(cfg):
    arts = api("repos/%s/actions/runs/%d/artifacts" % (cfg["repo"], cfg["run"]))
    for a in arts["artifacts"]:
        if a["name"] == cfg["artifact"]:
            with http(signed_url(a["archive_download_url"])) as r:
                z = zipfile.ZipFile(io.BytesIO(r.read()))
            names = [n for n in z.namelist() if n.endswith(".ini")]
            return names[0], z.read(names[0])
    raise SystemExit("artifact %s not found (expired?)" % cfg["artifact"])


def discover_miata():
    cfg = MIATA
    run = api("repos/%s/actions/runs/%d" % (cfg["repo"], cfg["run"]))
    member, data = artifact_bytes(cfg)
    e = {"file": "miata-ecus/%s" % member, "family": "miata-ecus", "board": "miata-ecu",
         "version": run["head_sha"][:10], "tags": [run["head_branch"]], "commit": run["head_sha"],
         "url": "%s/actions/runs/%d" % ("https://github.com/" + cfg["repo"], cfg["run"]),
         "member": cfg["artifact"] + "/" + member, "signature": ini_signature(data),
         "size": len(data), "sha256": sha256(data), "licence": cfg["licence"],
         "source": "https://github.com/%s/actions/runs/%d" % (cfg["repo"], cfg["run"])}
    store(e["file"], data)
    print("  %-48s %8d %s" % (e["file"], len(data), e["signature"]))
    save("miata-ecus", [e])


def fetch(fam):
    with open(manifest_path(fam), encoding="utf-8") as f:
        entries = json.load(f)
    bad = 0
    for e in entries:
        p = os.path.join(CACHE, e["file"])
        if os.path.exists(p):
            with open(p, "rb") as f:
                if sha256(f.read()) == e["sha256"]:
                    continue
        try:
            if fam == "miata-ecus":
                _, data = artifact_bytes(MIATA)
            elif e["member"]:
                _, data = zip_member(e["url"], "^" + re.escape(e["member"]) + "$")
            else:
                with http(e["url"]) as r:
                    data = r.read()
        except Exception as ex:      # noqa: BLE001 - report and continue with the others
            print("  FAILED %s: %s" % (e["file"], ex))
            bad += 1
            continue
        if sha256(data) != e["sha256"]:
            print("  CHANGED UPSTREAM %s (sha256 differs)" % e["file"])
            bad += 1
            continue
        store(e["file"], data)
        print("  %s" % e["file"])
    return bad


def main(argv):
    fams = ["speeduino", "rusefi", "fome", "miata-ecus"]
    if "--family" in argv:
        fams = [argv[argv.index("--family") + 1]]
    if "--discover" in argv:
        for fam in fams:
            print(fam)
            if fam == "speeduino":
                discover_speeduino()
            elif fam == "rusefi":
                discover_bundles("rusefi", RUSEFI)
            elif fam == "fome":
                discover_bundles("fome", FOME)
            elif fam == "miata-ecus":
                discover_miata()
        return 0
    bad = 0
    for fam in fams:
        print(fam)
        bad += fetch(fam)
    if bad:
        print("%d file(s) missing: python3 tools/gen_definitions.py --extract restores them from "
              "the committed bundle" % bad)
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
