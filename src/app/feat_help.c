/* feat_help.c - Help menu (Keyboard Shortcuts, Check for Updates, About), F1, and the shortcuts
 * list as a Settings page.  Worked example of dialog kinds, menu items, shortcuts and settings pages.
 * About lists the licences of everything built in, including the bundled ECU definitions (GPL-3.0
 * for rusEFI/FOME) and the CC BY-NC base tunes.
 * Check for Updates does not download anything: it shows the running version and build and opens
 * the releases page in the browser, where new versions are published.
 * SPDX-License-Identifier: GPL-2.0-or-later
 */
#include <string.h>
#include "feat.h"
#include "../tune/basetune.h"
#include "../project/inidb.h"

static void credit(lt_ui *ui, const char *title, const char *text)
{
    const lt_theme *t = lt_ui_theme(ui);
    int w1 = -1;
    lt_ui_layout_row(ui, 1, &w1, 0);
    lt_ui_text_style(ui, (int)LT_FONT_SANS_SEMIBOLD, LT_UI_FS_BASE);
    lt_ui_label_ex(ui, title, t->text, LT_UI_ALIGN_LEFT);
    lt_ui_text_style_reset(ui);
    lt_ui_layout_row(ui, 1, &w1, 0);
    lt_ui_label_wrap(ui, text, t->text2);
}

/* the bundled ECU definitions (project/inidb.h) */
static void about_definitions(lt_ui *ui)
{
    size_t i, n = lt_inidb_count(), gpl3 = 0;
    char buf[900];
    if (n == 0) { return; }
    for (i = 0; i < n; i++) {
        if (strstr(lt_inidb_at(i)->licence, "GPL-3.0") != NULL) { gpl3++; }
    }
    lt_snprintf(buf, sizeof(buf), "%lu ECU definition files (INI), embedded unmodified: Speeduino "
                "(https://github.com/speeduino/speeduino, GPL-2.0-or-later), rusEFI "
                "(https://github.com/rusefi/rusefi, GPL-3.0 with the rusEFI additional terms), FOME "
                "(https://github.com/FOME-Tech/fome-fw, GPL-3.0 with the same terms) and miata-ecus "
                "(https://github.com/v3ai/miata-ecus, generated by rusEFI, GPL-3.0). Sources, versions "
                "and commits: assets/definitions/README.md.", (unsigned long)n);
    credit(ui, "ECU definitions", buf);
    if (gpl3 > 0) {
        credit(ui, "This build is GPL-3.0", "Because it contains GPL-3.0 definition files, this "
               "program as a whole is distributed under the GNU General Public License, version 3; "
               "clibretune's own source code remains available under version 2 or later.");
    }
}

/* licences of everything built into the program */
static void about_credits(lt_ui *ui)
{
    const char *prov[16];
    char buf[700], who[300];
    size_t i, n;
    credit(ui, "clibretune", "Free software under the GNU General Public License, version 2 or later (LICENSE). "
           "Based on the original LibreTune project, https://github.com/RallyPat/LibreTune.");
    credit(ui, "Fonts", "IBM Plex Sans and IBM Plex Mono, Copyright 2017 IBM Corp., SIL Open Font License 1.1 "
           "(assets/fonts/OFL.txt). The 8x16 terminal font is derived from GNU Unifont (GPL-2.0-or-later "
           "with the font embedding exception); the legacy vector font uses Hershey fonts data.");
    credit(ui, "Icons", "Lucide icons, ISC License (assets/icons/LICENSE).");
    about_definitions(ui);
    if (lt_basetune_count() == 0) { return; }
    n = lt_basetune_providers(prov, LT_COUNTOF(prov));
    who[0] = '\0';
    for (i = 0; i < n && i < LT_COUNTOF(prov); i++) {
        if (!lt_basetune_named(prov[i])) { continue; }
        if (who[0] != '\0') { lt_strlcat(who, ", ", sizeof(who)); }
        lt_strlcat(who, prov[i], sizeof(who));
    }
    lt_strlcat(who, " and others", sizeof(who));
    lt_snprintf(buf, sizeof(buf), "The built-in base tunes are from the Speeduino Tunes repository, %s "
                "(commit %.10s), by the " LT_BASETUNE_AUTHORS "; tune authors: %s. They are NOT under the GPL: "
                "they are licensed under " LT_BASETUNE_LICENSE " (Creative Commons Attribution-NonCommercial "
                "4.0 International, " LT_BASETUNE_LICENSE_URL "), embedded unmodified, provided as is without "
                "warranty. Non-commercial: clibretune is never sold, and no bundle containing these tunes may be "
                "sold.", lt_basetune_source, lt_basetune_commit, who);
    credit(ui, "Speeduino base tunes", buf);
}

static void about_draw(lt_app *app, lt_app_dialog *d)
{
    lt_ui *ui = app->ui;
    const lt_theme *t = lt_ui_theme(ui);
    char msg[320];
    int w[2], w1 = -1;
    if (lt_ui_modal_begin(ui, "About clibretune", 680, 560, &d->open)) {
        lt_ui_layout_row(ui, 1, &w1, 0);
        lt_ui_text_style(ui, (int)LT_FONT_SANS_SEMIBOLD, LT_UI_FS_LG);
        lt_ui_label_ex(ui, "clibretune " LT_APP_VERSION, t->text, LT_UI_ALIGN_LEFT);
        lt_ui_text_style_reset(ui);
        lt_ui_layout_row(ui, 1, &w1, 0);
        lt_snprintf(msg, sizeof(msg), "Open source ECU tuning software, in Universal C.  Build: %s (" __DATE__
                    ")  UI scale: %d%%", lt_app_build_id(), app->scale_pct);
        lt_ui_label_ex(ui, msg, t->text2, LT_UI_ALIGN_LEFT);
        lt_ui_layout_row(ui, 1, &w1, 0);
        lt_ui_separator(ui);
        lt_ui_layout_row(ui, 1, &w1, lt_ui_cell_mode(ui) ? -20 : -40);
        if (lt_ui_scroll_begin(ui, "aboutlic")) {
            about_credits(ui);
            lt_ui_scroll_end(ui);
        }
        w[0] = -1; w[1] = 96;
        lt_ui_layout_row(ui, 2, w, 0);
        lt_ui_label_ex(ui, "Licences and credits", t->muted, LT_UI_ALIGN_LEFT);
        if (lt_ui_button_ex(ui, "OK", LT_UI_BTN_DEFAULT)) { d->open = 0; }
        lt_ui_modal_end(ui);
    }
}

static void keys_draw(lt_app *app, lt_app_dialog *d)
{
    lt_ui *ui = app->ui;
    int w[2], w1 = -1;
    if (lt_ui_modal_begin(ui, lt_tr("Keyboard shortcuts"), 720, 430, &d->open)) {
        lt_ui_layout_row(ui, 1, &w1, -36);
        if (lt_ui_scroll_begin(ui, "keysbody")) {
            lt_feat_hotkeys_grid(app);
            lt_ui_scroll_end(ui);
        }
        w[0] = -1; w[1] = 96;
        lt_ui_layout_row(ui, 2, w, 0);
        lt_ui_layout_next(ui);
        if (lt_ui_button_ex(ui, lt_tr("Close"), LT_UI_BTN_DEFAULT)) { d->open = 0; }
        lt_ui_modal_end(ui);
    }
}

#define LT_RELEASES_URL "https://github.com/v3ai/clibretune/releases"

typedef struct upd_state { char msg[200]; int err; } upd_state;

static upd_state *upd_get(lt_app *app)
{
    return (upd_state *)lt_ext_state(app, "updates", sizeof(upd_state), NULL);
}

static void updates_draw(lt_app *app, lt_app_dialog *d)
{
    lt_ui *ui = app->ui;
    const lt_theme *t = lt_ui_theme(ui);
    upd_state *s = upd_get(app);
    int w[3], w1 = -1, cell = lt_ui_cell_mode(ui);
    char b[200];
    if (lt_ui_modal_begin(ui, lt_tr("Check for Updates"), 640, 330, &d->open)) {
        w[0] = 160; w[1] = -1;
        lt_ui_layout_row(ui, 2, w, 0);
        lt_ui_label_ex(ui, lt_tr("Version:"), t->text2, LT_UI_ALIGN_LEFT);
        lt_ui_label(ui, "clibretune " LT_APP_VERSION);
        lt_ui_layout_row(ui, 2, w, 0);
        lt_ui_label_ex(ui, lt_tr("Build:"), t->text2, LT_UI_ALIGN_LEFT);
        lt_snprintf(b, sizeof(b), "%s (" __DATE__ ")", lt_app_build_id());
        lt_ui_label(ui, b);
        lt_ui_layout_row(ui, 2, w, 0);
        lt_ui_label_ex(ui, lt_tr("System:"), t->text2, LT_UI_ALIGN_LEFT);
        lt_ui_label(ui, lt_plat_os_name());
        lt_ui_layout_row(ui, 1, &w1, 0);
        lt_ui_label(ui, "");
        lt_ui_layout_row(ui, 1, &w1, 0);
        lt_ui_label_wrap(ui, lt_tr("clibretune does not update itself. New versions are published on the releases "
                                   "page: compare the version there with the one above, then download and install "
                                   "the new build the usual way for your system."), t->text);
        lt_ui_layout_row(ui, 1, &w1, 0);
        lt_ui_label_ex(ui, LT_RELEASES_URL, t->primary, LT_UI_ALIGN_LEFT);
        lt_ui_layout_row(ui, 1, &w1, cell ? -20 : -40);
        lt_ui_label_ex(ui, s->msg, s->err ? t->error : t->muted, LT_UI_ALIGN_LEFT);
        w[0] = -1; w[1] = 200; w[2] = 96;
        lt_ui_layout_row(ui, 3, w, 0);
        if (lt_ui_button(ui, lt_tr("Copy link"))) {
            lt_ui_clipboard_set(ui, LT_RELEASES_URL);
            lt_strlcpy(s->msg, lt_tr("Link copied to the clipboard"), sizeof(s->msg));
            s->err = 0;
        }
        if (lt_ui_button_ex(ui, lt_tr("Open releases page"), LT_UI_BTN_PRIMARY)) {
            if (lt_plat_open_url(LT_RELEASES_URL) == 0) {
                lt_strlcpy(s->msg, lt_tr("Opened in the web browser"), sizeof(s->msg));
                s->err = 0;
            } else {
                lt_strlcpy(s->msg, lt_tr("Cannot start a web browser here: copy the link instead"), sizeof(s->msg));
                s->err = 1;
            }
        }
        if (lt_ui_button_ex(ui, lt_tr("Close"), LT_UI_BTN_DEFAULT)) { d->open = 0; }
        lt_ui_modal_end(ui);
    }
    if (!d->open) { s->msg[0] = '\0'; }
}

static void act_updates(lt_app *app) { (void)lt_app_dialog_push(app, "updates", "", "Check for Updates"); }
static void act_about(lt_app *app) { (void)lt_app_dialog_push(app, "about", "", "About"); }
static void act_keys(lt_app *app) { (void)lt_app_dialog_push(app, "shortcuts", "", "Shortcuts"); }

void lt_feat_help_register(lt_app_ext *reg)
{
    lt_app_dialog_kind dk;
    dk.kind = "about"; dk.draw = about_draw; dk.close = NULL;
    lt_ext_add_dialog_kind(reg, &dk);
    dk.kind = "shortcuts"; dk.draw = keys_draw; dk.close = NULL;
    lt_ext_add_dialog_kind(reg, &dk);
    dk.kind = "updates"; dk.draw = updates_draw; dk.close = NULL;
    lt_ext_add_dialog_kind(reg, &dk);
    lt_ext_add_menu_item(reg, LT_EXT_MENU_HELP, "Keyboard &Shortcuts", NULL, act_keys, NULL);
    lt_ext_add_menu_item(reg, LT_EXT_MENU_HELP, "Check for &Updates...", NULL, act_updates, NULL);
    lt_ext_add_menu_item(reg, LT_EXT_MENU_HELP, "&About clibretune", NULL, act_about, NULL);
}
